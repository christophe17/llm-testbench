"""Evaluation suites: the arms `make eval` runs, declared in ``config/eval_suites.toml``.

An **arm** is one system under measurement. There are two kinds:

- a **retrieval arm** measures a search: a dataset, a retriever, and for a dense retriever
  the index it reads (how the documents are cut, which model embeds them, how the index is
  searched);
- a **generation arm** measures the generator: a question-answering dataset, where the
  passages handed to the generator come from (the gold ones, a search, nothing), and the
  index that search reads.

Every name says which kind it is about, in this module and in the ones around it
(``eval/retrieval.py``, ``eval/generation.py``, ``eval/cli.py``):

                        retrieval arm                  generation arm
    block of the file   [[suites.<suite>.retrieval]]   [[suites.<suite>.generation]]
    class               RetrievalArmConfig             GenerationArmConfig
    field of the suite  SuiteConfig.retrieval          SuiteConfig.generation
    dataset loader      load_retrieval_dataset         load_qa_dataset
    what runs it        run_retrieval_arm              run_generation_arm
    what comes out      RetrievalRun                   GenerationRun
    archived by         save_retrieval_run             save_generation_run
    read back by        load_retrieval_run             load_generation_run
    printed by          format_retrieval_runs          format_generation_run
    all of a suite's    run_retrieval_suite            run_generation_suite

``ArmConfig``, with no kind in its name, is what the two share: a name, a dataset and the
description of the index an arm reads when it reads one. ``ensure_index`` builds that index
for either kind.

Running an arm builds whatever it needs first, through the ingestion pipeline of phase 1:
an index that already exists costs nothing (idempotence), one that does not is built, and
the run records what the build took. A row of a results table is therefore regenerated by
its name alone.

Sample mode (``LLM_TESTBENCH_SAMPLE=1``, the CI): fixtures instead of the network, a
simulated embedder instead of a model, throwaway indexes with a ``sample-`` prefix, dropped
after the run. It checks that every arm runs end to end and nothing else.
"""

