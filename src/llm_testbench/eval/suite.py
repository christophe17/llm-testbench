SUITES_FILENAME = "eval_suites.toml"
SAMPLE_DIMENSIONS = 256
_SLUG = r"^[a-z0-9][a-z0-9-]{0,39}$"


_POOL = re.compile(r"^hotpotqa/pool-(\d+)$")


def hotpotqa_pool(dataset: str) -> int | None:
    """``hotpotqa/pool-1000`` -> 1000: the number of questions whose paragraphs make the
    corpus. ``None`` for any other dataset key."""
    match = _POOL.match(dataset)
    return int(match.group(1)) if match else None


class ArmConfig(BaseModel):
    """What every arm declares, whatever its kind: a name, a dataset and, when it reads an
    index, how that index is built (how the documents are cut, which model embeds them).
    An arm that reads no index (BM25, a generation arm on the gold context or with no
    context) leaves those fields unused. Not used on its own: an arm is a
    ``RetrievalArmConfig`` or a ``GenerationArmConfig``."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    name: str = Field(pattern=_SLUG)
    dataset: str
    """Dataset key: ``beir/scifact``, ``hotpotqa/pool-1000``, ``squad_v2``, ``qasper``."""

    embedding_model: str | None = None
    chunk_size: int = Field(default=1_000, ge=0)
    """In characters; ``0`` = do not cut (one chunk per document)."""
    chunk_overlap: int = Field(default=200, ge=0)
    index_key: str | None = None
    source_key: str | None = None
    """Pin an existing index (the one the API serves); derived from the arm otherwise."""

    @model_validator(mode="after")
    def _pins_go_together(self) -> "ArmConfig":
        if (self.index_key is None) != (self.source_key is None):
            raise ValueError(f"arm {self.name!r}: pin index_key and source_key together")
        return self

    @property
    def dataset_name(self) -> str:
        """The dataset as it appears in index and source keys: ``scifact``,
        ``hotpotqa-pool-1000`` (the pool size is part of what the index holds)."""
        return self.dataset.removeprefix("beir/").replace("/", "-")

    @property
    def whole_documents(self) -> bool:
        return self.chunk_size == 0

    def chunker(self) -> RecursiveChunker:
        if self.whole_documents:
            return RecursiveChunker(chunk_size=NO_SPLIT, chunk_overlap=0)
        return RecursiveChunker(chunk_size=self.chunk_size, chunk_overlap=self.chunk_overlap)

    def chunker_slug(self) -> str:
        return "whole" if self.whole_documents else f"r{self.chunk_size}-{self.chunk_overlap}"

    def keys(self, *, sample: bool = False) -> tuple[str, str]:
        """(index key, source key). The chunks of a source are shared by all its indexes
        (ADR 007), so another way of cutting is another source: the chunker is in the key."""
        if self.index_key is not None and self.source_key is not None and not sample:
            return self.index_key, self.source_key
        assert self.embedding_model is not None
        model = re.sub(r"[^a-z0-9]+", "-", self.embedding_model.rpartition("/")[2].lower())
        index_key = f"{self.dataset_name}-{self.chunker_slug()}-{model.strip('-')}"
        default_cut = RecursiveChunker()
        is_default = (self.chunk_size, self.chunk_overlap) == (
            default_cut.chunk_size,
            default_cut.chunk_overlap,
        )
        source_key = f"docs:{self.dataset_name}"
        if not is_default:
            source_key += f":{self.chunker_slug()}"
        if sample:
            return f"sample-{index_key}"[:63], f"sample:{source_key}"
        return index_key[:63], source_key


class RetrievalArmConfig(ArmConfig):
    """A retrieval arm: a retriever under measurement on a retrieval dataset. One
    ``[[suites.<suite>.retrieval]]`` block of the file."""

    split: str = "test"
    retriever: Literal["bm25", "dense"]
    search: SearchMode = "hnsw"
    ef_search: int | None = Field(default=None, ge=1, le=1_000)
    candidates: int | None = Field(default=None, ge=1)

    references: tuple[Reference, ...] = ()

    @model_validator(mode="after")
    def _dense_needs_a_model(self) -> "RetrievalArmConfig":
        if self.retriever == "dense" and self.embedding_model is None:
            raise ValueError(f"arm {self.name!r}: a dense retriever needs embedding_model")
        return self


class GenerationArmConfig(ArmConfig):
    """A generation arm: a generator under measurement on a QA dataset, fed the gold
    passages, what a search of the dataset's corpus returns (the end-to-end run), or
    nothing. One ``[[suites.<suite>.generation]]`` block of the file."""

    split: str = "validation"
    context: Literal["gold", "retrieved", "none"] = "gold"
    """``none``: the closed-book probe, the question without any document."""
    prompt: str = "chat_answer"
    """Name of the versioned prompt the generator is given."""
    top_k: int = Field(default=5, ge=1, le=50)
    """Retrieved context: the number of chunks handed to the generator (the API's default)."""
    max_examples: int | None = Field(default=None, ge=2)
    """Size of the random subsample (half answerable, half not); ``None`` = the whole split."""
    seed: int = 0
    generator: str | None = None
    """``backend/model``; the registry's default generator when left out."""
    repeats: int = Field(default=1, ge=1)
    repeat_examples: int = Field(default=0, ge=0)
    """Ask the first ``repeat_examples`` questions ``repeats`` times: non-determinism."""
    max_output_tokens: int | None = Field(default=None, ge=1)
    """Output cap of a call, reasoning included; the API's own cap when left out."""

    @model_validator(mode="after")
    def _a_search_needs_a_model(self) -> "GenerationArmConfig":
        if self.context == "retrieved" and self.embedding_model is None:
            raise ValueError(f"arm {self.name!r}: a retrieved context needs embedding_model")
        return self


class SuiteConfig(BaseModel):
    """A named group of arms, run by one command and read in one report: its retrieval
    arms and its generation arms, each kind under its own key of the file."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    description: str = ""
    metrics: tuple[str, ...] = DEFAULT_METRICS
    retrieval: tuple[RetrievalArmConfig, ...] = ()
    generation: tuple[GenerationArmConfig, ...] = ()

    @model_validator(mode="after")
    def _arm_names_are_unique(self) -> "SuiteConfig":
        names = self.arm_names()
        if not names:
            raise ValueError("a suite needs at least one arm")
        if len(set(names)) != len(names):
            raise ValueError("two arms of a suite share a name")
        return self

    def arm_names(self) -> list[str]:
        return [arm.name for arm in self.retrieval] + [arm.name for arm in self.generation]

    def select(
        self, names: list[str] | None
    ) -> tuple[tuple[RetrievalArmConfig, ...], tuple[GenerationArmConfig, ...]]:
        """(retrieval arms, generation arms) to run: all of them, or the named ones."""
        if not names:
            return self.retrieval, self.generation
        known = set(self.arm_names())
        missing = [name for name in names if name not in known]
        if missing:
            raise KeyError(f"unknown arm(s) {missing} (known: {sorted(known)})")
        return (
            tuple(arm for arm in self.retrieval if arm.name in names),
            tuple(arm for arm in self.generation if arm.name in names),
        )


class Budget(BaseModel):
    model_config = ConfigDict(frozen=True, extra="forbid")

    cap_usd: float = Field(default=10.0, gt=0)
    """Hard cap on what the harness spends, all runs together (``eval/spend.py``)."""


class Suites(BaseModel):
    model_config = ConfigDict(frozen=True)

    budget: Budget = Budget()
    suites: dict[str, SuiteConfig]

    @classmethod
    def load(cls, path: Path) -> "Suites":
        with path.open("rb") as handle:
            return cls.model_validate(tomllib.load(handle))

    @classmethod
    def from_settings(cls, settings: Settings | None = None) -> "Suites":
        settings = settings if settings is not None else get_settings()
        return cls.load(settings.resolved_config_dir() / SUITES_FILENAME)

    def get(self, name: str) -> SuiteConfig:
        try:
            return self.suites[name]
        except KeyError:
            raise KeyError(f"unknown suite {name!r} (known: {sorted(self.suites)})") from None


def load_retrieval_dataset(arm: RetrievalArmConfig, settings: Settings) -> RetrievalDataset:
    pool = hotpotqa_pool(arm.dataset)
    if pool is not None:
        return HotpotQALoader(settings).load_retrieval(arm.split, pool=pool)
    family, _, name = arm.dataset.partition("/")
    if family != "beir" or name not in BEIR_DATASETS:
        raise ValueError(f"arm {arm.name!r}: dataset {arm.dataset!r} has no loader")
    max_queries = settings.sample_max_queries if settings.sample else None
    return BeirLoader(name, settings).load(arm.split, max_queries=max_queries)


async def ensure_index(
    arm: ArmConfig,
    documents: Sequence[ParsedDocument],
    *,
    settings: Settings,
    client: LLMClient,
    store: PgVectorStore,
) -> tuple[IndexSpec, IndexBuild]:
    """The index an arm reads, built from ``documents`` if it is missing or incomplete."""
    assert arm.embedding_model is not None
    model = ModelRef.parse(arm.embedding_model)
    if settings.sample:
        # No model in CI: a deterministic bag of hashed words stands in for it.
        client.register_embedder(model.backend, HashingEmbedder(dimensions=SAMPLE_DIMENSIONS))
        dimensions: int | None = SAMPLE_DIMENSIONS
    else:
        dimensions = client.registry.embedding_dimensions(model)
    if dimensions is None:
        raise ValueError(
            f"arm {arm.name!r}: unknown vector size for {arm.embedding_model}; declare it "
            "under embedding_models in config/llm_backends.toml"
        )
    index_key, source_key = arm.keys(sample=settings.sample)
    pipeline = IngestionPipeline(
        client=client, store=store, chunker=arm.chunker(), data_class=DataClass.PUBLIC
    )
    cut = "whole documents" if arm.whole_documents else f"recursive({arm.chunker_slug()[1:]})"
    spec = pipeline.index_spec(
        index_key=index_key,
        source_key=source_key,
        embedding_model=arm.embedding_model,
        dimensions=dimensions,
        description=f"{arm.dataset_name} / {cut} / {arm.embedding_model}",
    )
    if settings.sample:
        await drop_sample_index(spec, store)
    started = time.perf_counter()
    report = await pipeline.ingest(spec, documents)
    build = IndexBuild(
        index_key=index_key,
        documents=report.documents_seen,
        chunks=report.chunks_total,
        chunks_embedded=report.chunks_embedded,
        embedding_tokens=report.embedding_tokens,
        cost_usd=report.cost_usd,
        seconds=time.perf_counter() - started,
    )
    return spec, build


async def drop_sample_index(spec: IndexSpec, store: PgVectorStore) -> None:
    if not spec.index_key.startswith("sample-"):
        raise ValueError(f"refusing to drop {spec.index_key!r}: not a sample index")
    await store.drop_index(spec.index_key)
    await store.delete_source(spec.source_key)


async def run_retrieval_arm(
    suite_name: str,
    suite: SuiteConfig,
    arm: RetrievalArmConfig,
    *,
    settings: Settings,
    client: LLMClient,
    store: PgVectorStore | None,
) -> RetrievalRun:
    dataset = load_retrieval_dataset(arm, settings)
    # Fixtures are smaller than any sample size, so the dataset itself cannot tell.
    sample_mode = settings.sample or settings.fixtures_dir is not None
    if arm.retriever == "bm25":
        lexical = BM25Retriever(dataset.documents)
        build = IndexBuild(
            index_key="in memory",
            documents=len(dataset.documents),
            chunks=len(dataset.documents),
            seconds=lexical.build_seconds,
        )
        return await run_retrieval(
            dataset,
            lexical,
            suite=suite_name,
            arm=arm.name,
            metrics=suite.metrics,
            references=arm.references,
            index=build,
            sample_mode=sample_mode,
        )
    if store is None:
        raise ValueError(f"arm {arm.name!r} reads a pgvector index: a database is required")
    spec, build = await ensure_index(
        arm, dataset.parsed_documents(), settings=settings, client=client, store=store
    )
    try:
        return await run_retrieval(
            dataset,
            DenseRetriever(
                client=client,
                store=store,
                spec=spec,
                search=arm.search,
                ef_search=arm.ef_search,
                candidates=arm.candidates,
            ),
            suite=suite_name,
            arm=arm.name,
            metrics=suite.metrics,
            references=arm.references,
            index=build,
            sample_mode=sample_mode,
        )
    finally:
        if settings.sample:
            await drop_sample_index(spec, store)


def load_qa_dataset(arm: GenerationArmConfig, settings: Settings) -> QADataset:
    pool = hotpotqa_pool(arm.dataset)
    if pool is not None:
        return HotpotQALoader(settings).load(
            arm.split, pool=pool, max_examples=arm.max_examples, seed=arm.seed
        )
    if arm.dataset == "qasper":
        return QasperLoader(settings).load_qa(
            arm.split, max_examples=arm.max_examples, seed=arm.seed
        )
    if arm.dataset == "squad_v2":
        return SquadV2Loader(settings).load(arm.split, max_examples=arm.max_examples, seed=arm.seed)
    raise ValueError(f"arm {arm.name!r}: dataset {arm.dataset!r} has no question-answering loader")


SIMULATED_ANSWER = "The answer is in the excerpt [1]."


async def run_generation_arm(
    suite_name: str,
    arm: GenerationArmConfig,
    *,
    settings: Settings,
    client: LLMClient,
    ledger: SpendLedger | None,
    store: PgVectorStore | None = None,
) -> GenerationRun:
    dataset = load_qa_dataset(arm, settings)
    model = ModelRef.parse(arm.generator) if arm.generator else client.registry.defaults.generator
    sample_mode = settings.sample or settings.fixtures_dir is not None
    if settings.sample:
        # No model in CI: the real provider code on a scripted network, one fixed answer.
        provider, _ = scripted_anthropic_provider(
            [
                Step(
                    json_body=anthropic_message(
                        SIMULATED_ANSWER, input_tokens=300, output_tokens=12
                    )
                )
            ],
            backend=model.backend,
        )
        client.register_provider(model.backend, provider)
    ledger = None if sample_mode else ledger
    context: ContextProvider | None = None
    spec: IndexSpec | None = None
    build: IndexBuild | None = None
    if arm.context == "retrieved":
        if store is None:
            raise ValueError(f"arm {arm.name!r} searches a pgvector index: a database is required")
        if not dataset.corpus:
            raise ValueError(f"arm {arm.name!r}: dataset {arm.dataset!r} has no corpus to search")
        if ledger is not None:
            ledger.check()
        spec, build = await ensure_index(
            arm, dataset.corpus, settings=settings, client=client, store=store
        )
        if ledger is not None:
            ledger.charge(build.cost_usd, f"{arm.name} / index")
        context = RetrievedContext(
            DocumentSource(client=client, store=store, spec=spec), k=arm.top_k
        )
    elif arm.context == "none":
        context = NoContext()
    try:
        return await run_generation(
            dataset,
            client=client,
            builder=AnswerBuilder(PromptRegistry.from_settings(settings), prompt_name=arm.prompt),
            model=model,
            suite=suite_name,
            arm=arm.name,
            context=context,
            index=build,
            repeats=arm.repeats,
            repeat_examples=arm.repeat_examples,
            max_output_tokens=arm.max_output_tokens or MAX_OUTPUT_TOKENS,
            ledger=ledger,
            sample_mode=sample_mode,
        )
    finally:
        if settings.sample and spec is not None and store is not None:
            await drop_sample_index(spec, store)
